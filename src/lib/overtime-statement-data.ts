import { prisma } from "@/lib/prisma";
import { getDb } from "@/lib/data";
import { employeesInScope, viewerScope } from "@/lib/scope";
import { buildOvertimeStatement, type OvertimeStatement } from "@/lib/overtime-statement";
import type { User } from "@/lib/types";

/**
 * The overtime statement of [from, to] for what `user` may see: their scope's employees only (a department
 * supervisor gets their department), checked here on the server for the page and the export alike. Read only.
 */
export async function loadOvertimeStatement(user: User, from: string, to: string, locale: "ar" | "en"): Promise<OvertimeStatement> {
  const db = await getDb();
  const employees = employeesInScope(viewerScope(user, db.employees), db.employees);
  const rows = await prisma.overtime.findMany({
    where: {
      employeeId: { in: employees.map((e) => e.id) },
      date: { gte: new Date(`${from}T00:00:00.000Z`), lte: new Date(`${to}T00:00:00.000Z`) },
    },
    select: { employeeId: true, hours: true, amount: true, status: true, kind: true, autoGenerated: true, voidedAt: true },
  });
  return buildOvertimeStatement({ rows, employees, departments: db.departments, locale });
}
