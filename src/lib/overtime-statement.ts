import { terminatedLast } from "@/lib/employee-order";
import { addDays } from "@/lib/today";

/** Overtime is paid out on this day of every month… */
export const OVERTIME_PAYDAY = 20;
/** …for the work from this day of the month before, up to and including the payday. */
export const OVERTIME_PERIOD_START_DAY = OVERTIME_PAYDAY + 1;

const pad = (n: number) => String(n).padStart(2, "0");

/** The statement's default dates for `year`/`month`: the 21st of the month before to the 20th of this one. */
export function defaultStatementRange(year: number, month: number): { from: string; to: string } {
  const prevYear = month === 1 ? year - 1 : year;
  const prevMonth = month === 1 ? 12 : month - 1;
  return {
    from: `${prevYear}-${pad(prevMonth)}-${pad(OVERTIME_PERIOD_START_DAY)}`,
    to: `${year}-${pad(month)}-${pad(OVERTIME_PAYDAY)}`,
  };
}

/** A calendar day, yyyy-MM-dd, that really exists. */
export function isDay(value: string | undefined | null): value is string {
  if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  return addDays(value, 0) === value;
}

/**
 * The statement's month and dates from the query string: `month=yyyy-MM` (default: `now`), `from` / `to`
 * (default: that month's 21st → 20th). Dates that aren't real days fall back to the default; `from` after `to`
 * is reported, not swapped.
 */
export function statementParams(
  raw: { month?: string | null; from?: string | null; to?: string | null },
  now: { year: number; month: number },
): { year: number; month: number; from: string; to: string; invalidRange: boolean } {
  const m = /^(\d{4})-(\d{2})$/.exec(raw.month ?? "");
  const valid = m !== null && Number(m[2]) >= 1 && Number(m[2]) <= 12;
  const year = valid ? Number(m[1]) : now.year;
  const month = valid ? Number(m[2]) : now.month;
  const fallback = defaultStatementRange(year, month);
  const from = isDay(raw.from) ? raw.from : fallback.from;
  const to = isDay(raw.to) ? raw.to : fallback.to;
  return { year, month, from, to, invalidRange: from > to };
}

/**
 * The columns the statement splits an employee's overtime into. The system posts "overtime", "friday",
 * "holiday" and "thursday_extra" (Overtime.kind); an entry made by hand is stored as kind "overtime" with
 * autoGenerated = false, so it is told apart by that and shown as "manual".
 */
export const STATEMENT_KINDS = ["overtime", "friday", "holiday", "thursday_extra", "manual"] as const;
export type StatementKind = (typeof STATEMENT_KINDS)[number];

export interface StatementSourceRow {
  employeeId: string;
  hours: number;
  amount: number;
  status: string;
  kind: string | null;
  autoGenerated: boolean;
  voidedAt: Date | string | null;
}

export interface StatementLine {
  employeeId: string;
  employeeNumber: string;
  name: string;
  departmentId: string;
  department: string;
  terminated: boolean;
  hours: number;
  amount: number;
  byKind: Record<StatementKind, number>;
}

export interface OvertimeStatement {
  lines: StatementLine[];
  total: { hours: number; amount: number; byKind: Record<StatementKind, number> };
  /** Entries in the period still waiting for approval — not counted, only reported. */
  pendingCount: number;
}

export function statementKindOf(row: Pick<StatementSourceRow, "kind" | "autoGenerated">): StatementKind {
  if (!row.autoGenerated) return "manual";
  return (STATEMENT_KINDS as readonly string[]).includes(row.kind ?? "") ? (row.kind as StatementKind) : "overtime";
}

const emptyKinds = (): Record<StatementKind, number> => ({ overtime: 0, friday: 0, holiday: 0, thursday_extra: 0, manual: 0 });
const round2 = (n: number) => Math.round(n * 100) / 100;

/**
 * One line per employee with approved overtime among `rows` (already limited to the period and to the viewer's
 * employees): their hours and amount, and the amount by kind — straight from the stored Overtime fields, nothing
 * recalculated. Removed (voided) entries never count; pending ones are only counted in `pendingCount`; rejected
 * ones are left out. Terminated employees come last; an archived one is listed like anyone else.
 */
export function buildOvertimeStatement(input: {
  rows: StatementSourceRow[];
  employees: Employee[];
  departments: Department[];
  locale: "ar" | "en";
}): OvertimeStatement {
  const employeeById = new Map(input.employees.map((e) => [e.id, e]));
  const deptName = new Map(input.departments.map((d) => [d.id, d.name]));
  const live = input.rows.filter((r) => !r.voidedAt && employeeById.has(r.employeeId));

  const byEmployee = new Map<string, StatementLine>();
  for (const row of live) {
    if (row.status !== "approved") continue;
    const e = employeeById.get(row.employeeId)!;
    const line =
      byEmployee.get(e.id) ??
      ({
        employeeId: e.id,
        employeeNumber: e.employeeNumber,
        name: e.name,
        departmentId: e.departmentId,
        department: translateLabel(deptName.get(e.departmentId) ?? "-", input.locale),
        terminated: e.status === "terminated",
        hours: 0,
        amount: 0,
        byKind: emptyKinds(),
      } satisfies StatementLine);
    line.hours = round2(line.hours + row.hours);
    line.amount += row.amount;
    line.byKind[statementKindOf(row)] += row.amount;
    byEmployee.set(e.id, line);
  }

  const lines = [...byEmployee.values()].sort(
    (a, b) =>
      terminatedLast(employeeById.get(a.employeeId), employeeById.get(b.employeeId)) ||
      a.name.localeCompare(b.name, input.locale === "ar" ? "ar" : "en"),
  );
  const total = { hours: 0, amount: 0, byKind: emptyKinds() };
  for (const l of lines) {
    total.hours = round2(total.hours + l.hours);
    total.amount += l.amount;
    for (const k of STATEMENT_KINDS) total.byKind[k] += l.byKind[k];
  }
  return { lines, total, pendingCount: live.filter((r) => r.status === "pending").length };
}

export function statementKindLabel(kind: StatementKind, t: Dictionary): string {
  switch (kind) {
    case "friday":
      return t.overtime.kindFriday;
    case "holiday":
      return t.overtime.kindHoliday;
    case "thursday_extra":
      return t.overtime.kindThursday;
    case "manual":
      return t.overtime.statement.kindManual;
    default:
      return t.overtime.kindOvertime;
  }
}

/** The sheet: a header row, one row per employee with the table's columns, then the total row. Amounts are numbers. */
export function overtimeStatementSheet(statement: OvertimeStatement, t: Dictionary): { headers: string[]; rows: (string | number)[][] } {
  const headers = [
    t.payslip.employeeId,
    t.payslip.employeeName,
    t.payslip.department,
    t.overtime.statement.colHours,
    t.overtime.statement.colAmount,
    ...STATEMENT_KINDS.map((k) => statementKindLabel(k, t)),
  ];
  const rows = statement.lines.map((l) => [
    l.employeeNumber,
    l.name,
    l.department,
    l.hours,
    l.amount,
    ...STATEMENT_KINDS.map((k) => l.byKind[k]),
  ]);
  rows.push([t.overtime.statement.total, "", "", statement.total.hours, statement.total.amount, ...STATEMENT_KINDS.map((k) => statement.total.byKind[k])]);
  return { headers, rows };
}

/** `overtime-statement-2026-10.xlsx` — no company name in it. */
export function overtimeStatementFileName(year: number, month: number): string {
  return `overtime-statement-${year}-${pad(month)}.xlsx`;
}

/** "12:30" for 12.5 hours. */
export function hoursLabel(hours: number): string {
  const minutes = Math.round(hours * 60);
  return `${Math.floor(minutes / 60)}:${pad(minutes % 60)}`;
}
