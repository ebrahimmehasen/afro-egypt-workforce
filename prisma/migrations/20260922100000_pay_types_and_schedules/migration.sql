-- Existing employees keep exactly what they had: the pay type matching their pay basis, and the schedule
-- matching their shift's times — or, when no schedule matches (evening / night shifts), their shift's own
-- times as custom times.
UPDATE `Employee` SET `payTypeId` = CONCAT('paytype-', `salaryType`) WHERE `payTypeId` IS NULL;
UPDATE `Employee` e JOIN `Shift` s ON s.`id` = e.`shiftId`
    JOIN `WorkSchedule` w ON w.`startTime` = s.`startTime` AND w.`endTime` = s.`endTime` AND w.`deletedAt` IS NULL
    SET e.`workScheduleId` = w.`id`
    WHERE e.`workScheduleId` IS NULL AND e.`customWorkStart` IS NULL;
UPDATE `Employee` e JOIN `Shift` s ON s.`id` = e.`shiftId`
    SET e.`customWorkStart` = s.`startTime`, e.`customWorkEnd` = s.`endTime`
    WHERE e.`workScheduleId` IS NULL AND e.`customWorkStart` IS NULL;
