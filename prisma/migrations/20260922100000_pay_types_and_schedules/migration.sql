ALTER TABLE `AttendanceSettings` ADD COLUMN `weeklyOffDays` VARCHAR(191) NOT NULL DEFAULT '5';
ALTER TABLE `PayrollSettings` ADD COLUMN `payPeriodStartDay` INTEGER NOT NULL DEFAULT 26;

