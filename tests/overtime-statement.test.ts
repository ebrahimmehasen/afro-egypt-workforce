import { afterAll, describe, expect, it } from "vitest";
import { PrismaClient } from "@prisma/client";
import {
  OVERTIME_PAYDAY,
  OVERTIME_PERIOD_START_DAY,
  STATEMENT_KINDS,
  buildOvertimeStatement,
  defaultStatementRange,
  hoursLabel,
  overtimeStatementFileName,
  overtimeStatementSheet,
  statementParams,
  type StatementSourceRow,
} from "@/lib/overtime-statement";
import { getDictionary } from "@/lib/i18n";
import { canAccess, hasPermission, isSelfService } from "@/lib/permissions";
import { employeesInScope, viewerScope } from "@/lib/scope";
import { COMPANY } from "@/lib/constants";
import type { Department, Employee, User } from "@/lib/types";

const t = getDictionary("ar");

const emp = (id: string, name: string, over: Partial<Employee> = {}): Employee =>
  ({ id, employeeNumber: `N-${id}`, name, departmentId: "D1", jobTitle: "x", hireDate: "2024-01-01", shiftId: "s", salaryType: "monthly", basicSalary: 6000, dailyWorkingHours: 8, allowances: 0, status: "active", ...over }) as Employee;
const departments: Department[] = [{ id: "D1", name: "الإنتاج", managerName: "" }, { id: "D2", name: "المخازن", managerName: "" }];
const row = (employeeId: string, over: Partial<StatementSourceRow> = {}): StatementSourceRow => ({
  employeeId,
  hours: 2,
  amount: 100,
  status: "approved",
  kind: "overtime",
  autoGenerated: true,
  voidedAt: null,
  ...over,
});
const build = (rows: StatementSourceRow[], employees: Employee[]) => buildOvertimeStatement({ rows, employees, departments, locale: "ar" });

describe("the default period: the 21st of the month before to the 20th", () => {
  it("the payday and the start day are one named pair", () => {
    expect(OVERTIME_PAYDAY).toBe(20);
    expect(OVERTIME_PERIOD_START_DAY).toBe(21);
  });

  it("an ordinary month, January (back into December of the year before) and December", () => {
    expect(defaultStatementRange(2026, 10)).toEqual({ from: "2026-09-21", to: "2026-10-20" });
    expect(defaultStatementRange(2026, 1)).toEqual({ from: "2025-12-21", to: "2026-01-20" });
    expect(defaultStatementRange(2026, 12)).toEqual({ from: "2026-11-21", to: "2026-12-20" });
  });

  it("reads month and dates from the query, falls back to the defaults, and reports from after to", () => {
    expect(statementParams({}, { year: 2026, month: 10 })).toEqual({ year: 2026, month: 10, from: "2026-09-21", to: "2026-10-20", invalidRange: false });
    expect(statementParams({ month: "2027-01" }, { year: 2026, month: 10 })).toMatchObject({ year: 2027, month: 1, from: "2026-12-21", to: "2027-01-20" });
    expect(statementParams({ month: "2026-10", from: "2026-10-01", to: "2026-10-31" }, { year: 2026, month: 10 })).toMatchObject({ from: "2026-10-01", to: "2026-10-31" });
    expect(statementParams({ month: "2026-13", from: "2026-02-30" }, { year: 2026, month: 10 })).toMatchObject({ month: 10, from: "2026-09-21" });
    expect(statementParams({ from: "2026-10-20", to: "2026-10-01" }, { year: 2026, month: 10 }).invalidRange).toBe(true);
  });
});

describe("the statement", () => {
  it("counts approved overtime only: removed, pending and rejected entries are left out, pending ones reported", () => {
    const s = build(
      [
        row("a"),
        row("a", { voidedAt: new Date() }),
        row("a", { status: "pending" }),
        row("a", { status: "pending" }),
        row("a", { status: "pending", voidedAt: new Date() }),
        row("a", { status: "rejected" }),
      ],
      [emp("a", "أحمد")],
    );
    expect(s.lines).toHaveLength(1);
    expect(s.lines[0]).toMatchObject({ hours: 2, amount: 100 });
    expect(s.pendingCount).toBe(2);
  });

  it("one line per employee, with the amount split by kind — a hand-made entry under manual", () => {
    const s = build(
      [
        row("a", { kind: "overtime", amount: 100, hours: 2 }),
        row("a", { kind: "friday", amount: 300, hours: 5 }),
        row("a", { kind: "holiday", amount: 200, hours: 3.5 }),
        row("a", { kind: "thursday_extra", amount: 50, hours: 1 }),
        row("a", { kind: "overtime", autoGenerated: false, amount: 75, hours: 1.25 }),
        row("b", { amount: 40, hours: 0.5 }),
      ],
      [emp("a", "أحمد"), emp("b", "بسمة", { departmentId: "D2" })],
    );
    expect(s.lines.map((l) => l.employeeId)).toEqual(["a", "b"]);
    expect(s.lines[0].byKind).toEqual({ overtime: 100, friday: 300, holiday: 200, thursday_extra: 50, manual: 75 });
    expect(s.lines[0]).toMatchObject({ hours: 12.75, amount: 725, department: "الإنتاج" });
    expect(s.lines[1]).toMatchObject({ hours: 0.5, amount: 40, department: "المخازن" });
    expect(s.total).toEqual({ hours: 13.25, amount: 765, byKind: { overtime: 140, friday: 300, holiday: 200, thursday_extra: 50, manual: 75 } });
  });

  it("nobody without approved overtime is listed; terminated employees come last; an archived one is listed", () => {
    const s = build(
      [row("z"), row("t"), row("ar"), row("p", { status: "pending" })],
      [emp("z", "زياد"), emp("t", "تامر", { status: "terminated" }), emp("ar", "أمل", { archivedAt: "2026-01-01" } as Partial<Employee>), emp("p", "بلال")],
    );
    expect(s.lines.map((l) => l.name)).toEqual(["أمل", "زياد", "تامر"]);
  });

  it("hours read as h:mm", () => {
    expect(hoursLabel(12.75)).toBe("12:45");
    expect(hoursLabel(0.5)).toBe("0:30");
  });
});

describe("the export sheet", () => {
  const s = build([row("a", { amount: 120, hours: 3 }), row("b", { kind: "friday", amount: 80, hours: 1.5 })], [emp("a", "أحمد"), emp("b", "بسمة")]);
  const { headers, rows } = overtimeStatementSheet(s, t);

  it("a header row, the table's columns, one row per employee then the total — amounts as numbers", () => {
    expect(headers[0]).toBe(t.payslip.employeeId);
    expect(headers).toHaveLength(5 + STATEMENT_KINDS.length);
    expect(rows).toHaveLength(3);
    expect(rows.map((r) => r[1])).toEqual(["أحمد", "بسمة", ""]);
    for (const r of rows) for (let i = 3; i < headers.length; i++) expect(typeof r[i]).toBe("number");
    expect(rows[2].slice(3, 5)).toEqual([4.5, 200]);
  });

  it("nothing about the company, and a file name without it", () => {
    const text = JSON.stringify({ headers, rows });
    for (const brand of [COMPANY.name, COMPANY.logo, COMPANY.productName, "Afro", "404"]) expect(text).not.toContain(brand);
    expect(overtimeStatementFileName(2026, 1)).toBe("overtime-statement-2026-01.xlsx");
  });
});

/** Who may open it (page and export): requireAccess("/overtime/statement"), then the "overtime" permission. */
const user = (over: Partial<User>): User => ({ id: "U", name: "U", email: "u@x.com", role: "employee", permissions: [], ...over });
const mayOpen = (u: User) => canAccess(u, "/overtime/statement") && hasPermission(u, "overtime");

describe("who may see the statement", () => {
  it("an admin may", () => {
    expect(mayOpen(user({ role: "admin" }))).toBe(true);
  });

  it("an account granted overtime may", () => {
    for (const role of ["hr", "supervisor", "staff"] as const) expect(mayOpen(user({ role, permissions: ["overtime"] }))).toBe(true);
  });

  it("an account without the overtime permission may not", () => {
    for (const role of ["hr", "supervisor", "staff"] as const) {
      const u = user({ role, permissions: ["employees", "payroll"] });
      expect(canAccess(u, "/overtime/statement")).toBe(false);
      expect(mayOpen(u)).toBe(false);
    }
  });

  it("a self-service employee may not", () => {
    const self = user({ role: "employee", employeeId: "E1" });
    expect(isSelfService(self)).toBe(true);
    expect(canAccess(self, "/overtime/statement")).toBe(false);
    expect(mayOpen(self)).toBe(false);
  });
});

const prisma = new PrismaClient();
let sampleLoaded = false;
let roster: Employee[] = [];
let deptA = "";
try {
  roster = (await prisma.employee.findMany({ where: { deletedAt: null }, select: { id: true, departmentId: true } })) as unknown as Employee[];
  deptA = roster[0]?.departmentId ?? "";
  sampleLoaded = roster.length >= 10 && roster.some((e) => e.departmentId !== deptA);
} catch {
  sampleLoaded = false;
}
afterAll(async () => {
  await prisma.$disconnect();
});

describe.skipIf(!sampleLoaded)("whose overtime the statement reads: the viewer's scope", () => {
  it("a department supervisor with overtime gets only their department's employees", () => {
    const kept = employeesInScope(viewerScope(user({ role: "supervisor", permissions: ["overtime"], departmentIds: [deptA] }), roster), roster);
    expect(kept.length).toBeGreaterThan(0);
    expect(kept.length).toBeLessThan(roster.length);
    expect(kept.every((e) => e.departmentId === deptA)).toBe(true);
  });

  it("an admin, or an overtime account without a department limit, gets everyone", () => {
    for (const u of [user({ role: "admin" }), user({ role: "hr", permissions: ["overtime"] })]) {
      expect(employeesInScope(viewerScope(u, roster), roster)).toHaveLength(roster.length);
    }
  });
});
