import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { PrismaClient } from "@prisma/client";
import {
  OVERTIME_INELIGIBLE_VOIDED_BY,
  eligibleOvertimeRestores,
  ineligibleOvertimeVoids,
  systemEntriesFor,
} from "@/lib/attendance-deductions";
import { FALLBACK_PAY_TYPES } from "@/lib/pay-defaults";
import type { PayEmployee } from "@/lib/pay-context";

/**
 * Switching "له إضافي" off takes effect backwards: every addition of the employee on a day that can still change
 * (not in an approved or closed pay month) is removed — voided, never deleted — whatever its kind, the system's
 * or entered by hand, edited or not. Switching it back on hands the system's ones back to the automatic posting;
 * hand-made ones stay removed. The database part runs the real applyUpdateEmployee against the sample-seeded dev
 * database on a temporary employee, and skips itself anywhere else.
 */

const row = (over: Partial<Parameters<typeof ineligibleOvertimeVoids>[0][number]>) => ({
  id: "r",
  date: "2030-05-10",
  amount: 100,
  autoGenerated: true,
  voidedAt: null,
  voidedBy: null,
  ...over,
});
const lockedMarch = (day: string) => day >= "2030-02-26" && day <= "2030-03-25";

describe("which additions the switch touches (pure)", () => {
  it("off: every standing addition on an open day — auto, manual, edited — and nothing on a locked day", () => {
    const rows = [
      row({ id: "auto" }),
      row({ id: "manual", autoGenerated: false }),
      row({ id: "locked", date: "2030-03-10" }),
      row({ id: "already", voidedAt: new Date(), voidedBy: "someone" }),
    ];
    expect(ineligibleOvertimeVoids(rows, lockedMarch).map((r) => r.id)).toEqual(["auto", "manual"]);
  });

  it("on: only the system's additions removed by the switch, on open days", () => {
    const off = { voidedAt: new Date(), voidedBy: OVERTIME_INELIGIBLE_VOIDED_BY };
    const rows = [
      row({ id: "auto", ...off }),
      row({ id: "manual", autoGenerated: false, ...off }),
      row({ id: "byHand", voidedAt: new Date(), voidedBy: "someone" }),
      row({ id: "locked", date: "2030-03-10", ...off }),
      row({ id: "standing" }),
    ];
    expect(eligibleOvertimeRestores(rows, lockedMarch).map((r) => r.id)).toEqual(["auto"]);
  });
});

describe("the automatic posting for an employee whose له إضافي is off", () => {
  it("posts no addition at all, and still charges lateness and leaving early", () => {
    const rules = { ...FALLBACK_PAY_TYPES.monthly, id: "pt", hoursPerDay: 10, graceMinutes: 0 };
    const schedule = { start: "08:00", end: "18:00", overtimeStart: "18:00" };
    const day = (date: string, inT: string, outT: string) => ({
      employeeId: "E",
      date,
      status: "present",
      actualIn: new Date(`${date}T${inT}:00`),
      actualOut: new Date(`${date}T${outT}:00`),
      scheduledStart: new Date(`${date}T08:00:00`),
    });
    const employee = (eligible: boolean) => ({ id: "E", basicSalary: 6000, dailyRate: null, overtimeEligible: eligible }) as unknown as PayEmployee;
    // late in, overtime out on a working day; then a weekly day off worked
    const workday = day("2030-05-13", "08:30", "20:30");
    const friday = day("2030-05-17", "08:00", "12:00");
    const off = [systemEntriesFor(workday, employee(false), rules, schedule, "workday", null), systemEntriesFor(friday, employee(false), rules, schedule, "weekly_off", null)];
    expect(off.flatMap((e) => e.additions)).toEqual([]);
    expect(off[0].deductions.map((d) => d.type)).toEqual(["late"]);
    const on = systemEntriesFor(workday, employee(true), rules, schedule, "workday", null);
    expect(on.additions.map((a) => a.kind)).toEqual(["overtime"]);
  });
});

