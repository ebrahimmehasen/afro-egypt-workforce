vi.mock("next/headers", () => ({ cookies: async () => ({ get: () => undefined, set: () => {}, delete: () => {} }) }));
vi.mock("next/cache", () => ({ revalidatePath: () => {} }));
vi.mock("next/navigation", () => ({ redirect: () => {} }));
vi.mock("@/lib/auth", () => ({ getSession: async () => null }));
vi.mock("@/lib/pay-refresh", () => ({ refreshPayCalculations: () => {} }));
const effects = vi.hoisted(() => ({ calls: [] as unknown[] }));
vi.mock("@/lib/attendance-effects", () => ({ scheduleAttendanceEffects: (opts: unknown) => effects.calls.push(opts), runAttendanceEffects: async () => ({}) }));

const { applyUpdateEmployee } = await import("@/lib/actions/employees");

const prisma = new PrismaClient();
let sampleDb = false;
try {
  sampleDb = Boolean(await prisma.user.findUnique({ where: { email: "hr@afroegypt.demo" } }));
} catch {
  sampleDb = false;
}

const EMP = "ZZ-OTSW-001";
const ACTOR = "overtime-switch-test";
// an approved pay month far from anything else the tests touch: with the 26th start day, 2097-03 is 2097-02-26 → 2097-03-25
const LOCKED = { year: 2097, month: 3 };
const OPEN_DAY = "2097-05-10";
const LOCKED_DAY = "2097-03-10";

async function cleanUp() {
  await prisma.overtime.deleteMany({ where: { employeeId: EMP } });
  await prisma.employee.deleteMany({ where: { id: EMP } });
  await prisma.payrollPeriod.deleteMany({ where: LOCKED });
  await prisma.auditLogEntry.deleteMany({ where: { userName: ACTOR } });
}

async function payload(overtimeEligible: boolean) {
  const e = await prisma.employee.findUniqueOrThrow({ where: { id: EMP } });
  return {
    id: EMP,
    name: e.name,
    departmentId: e.departmentId,
    jobTitle: e.jobTitle,
    hireDate: e.hireDate.toISOString().slice(0, 10),
    shiftId: e.shiftId,
    salaryType: e.salaryType,
    basicSalary: e.basicSalary,
    dailyWorkingHours: e.dailyWorkingHours,
    overtimeEligible,
    allowances: e.allowancesTotal,
    status: e.status,
    phone: null,
    address: null,
    qualification: null,
    militaryStatus: null,
    nationalId: null,
    isDriver: false,
  };
}

const addition = (over: Record<string, unknown>) =>
  prisma.overtime.create({
    data: { employeeId: EMP, date: new Date(`${OPEN_DAY}T00:00:00.000Z`), hours: 2, hourlyRate: 50, amount: 100, status: "approved", ...over },
  });
const stateOf = async (id: string) => prisma.overtime.findUniqueOrThrow({ where: { id } });

afterAll(async () => {
  if (sampleDb) await cleanUp();
  await prisma.$disconnect();
});

describe.skipIf(!sampleDb)("switching له إضافي on an employee", () => {
  beforeAll(async () => {
    await cleanUp();
    const seed = await prisma.employee.findFirstOrThrow({ where: { deletedAt: null, id: { startsWith: "EMP-" } }, orderBy: { id: "asc" } });
    await prisma.employee.create({
      data: { id: EMP, employeeNumber: "ZZOTSW-001", name: "اختبار مفتاح الإضافي", departmentId: seed.departmentId, jobTitle: "x", hireDate: new Date("2024-01-01"), shiftId: seed.shiftId, basicSalary: 6000, overtimeEligible: true },
    });
    await prisma.payrollPeriod.create({ data: { label: "اختبار مفتاح الإضافي", ...LOCKED, status: "approved" } });
  });
  beforeEach(() => {
    effects.calls.length = 0;
  });

  it("off: voids every addition on open days — auto, manual, edited — and leaves the approved month alone", async () => {
    const auto = await addition({ autoGenerated: true, systemKey: `${EMP}|${OPEN_DAY}|overtime`, kind: "overtime" });
    const friday = await addition({ autoGenerated: true, systemKey: `${EMP}|${OPEN_DAY}|friday`, kind: "friday", status: "pending" });
    const edited = await addition({ autoGenerated: true, systemKey: `${EMP}|${OPEN_DAY}|thursday_extra`, kind: "thursday_extra", editedAt: new Date(), editedBy: "x", originalAmount: 80 });
    const manual = await addition({ autoGenerated: false, status: "pending" });
    const locked = await addition({ autoGenerated: true, systemKey: `${EMP}|${LOCKED_DAY}|overtime`, kind: "overtime", date: new Date(`${LOCKED_DAY}T00:00:00.000Z`) });

    expect(await applyUpdateEmployee(await payload(false), ACTOR)).toMatchObject({ success: true });

    for (const r of [auto, friday, edited, manual]) {
      const now = await stateOf(r.id);
      expect(now.voidedAt).not.toBeNull();
      expect(now.voidedBy).toBe(OVERTIME_INELIGIBLE_VOIDED_BY);
      // voided, not changed: the values (and the calculated original) stay on record
      expect(now.amount).toBe(100);
    }
    expect((await stateOf(edited.id)).originalAmount).toBe(80);
    expect((await stateOf(locked.id)).voidedAt).toBeNull();
    const audit = await prisma.auditLogEntry.findFirstOrThrow({ where: { userName: ACTOR, oldValue: { contains: "EGP" } } });
    expect(audit.oldValue).toBe("4 — 400 EGP");
    expect(effects.calls).toEqual([{ payrollChanged: true }]);
  });

  it("on: hands the system's additions back to the posting; the hand-made one and the locked month stay as they are", async () => {
    expect(await applyUpdateEmployee(await payload(true), ACTOR)).toMatchObject({ success: true });
    const rows = await prisma.overtime.findMany({ where: { employeeId: EMP } });
    const auto = rows.filter((r) => r.autoGenerated && r.date.toISOString().startsWith(OPEN_DAY));
    expect(auto).toHaveLength(3);
    for (const r of auto) {
      expect(r.voidedAt).toBeNull();
      // no longer "edited": the posting works it out again
      expect(r.editedAt).toBeNull();
    }
    const manual = rows.find((r) => !r.autoGenerated)!;
    expect(manual.voidedAt).not.toBeNull();
    expect(rows.find((r) => r.date.toISOString().startsWith(LOCKED_DAY))!.voidedAt).toBeNull();
    expect(effects.calls).toEqual([{ payrollChanged: true }]);
  });

  it("an edit that doesn't touch له إضافي changes no addition and posts nothing extra", async () => {
    const before = await prisma.overtime.findMany({ where: { employeeId: EMP }, orderBy: { id: "asc" } });
    expect(await applyUpdateEmployee(await payload(true), ACTOR)).toMatchObject({ success: true });
    expect(await prisma.overtime.findMany({ where: { employeeId: EMP }, orderBy: { id: "asc" } })).toEqual(before);
    expect(effects.calls).toEqual([]);
  });
});
