function rec(id: string, periodId: string, employeeId: string, basic: number, allowances: number, overtime: number, deductions: number) {
  const gross = basic + allowances + overtime;
  return {
    id, periodId, employeeId, basicSalary: basic, allowances, overtimeAmount: overtime, incentives: 0, bonuses: 0, grossSalary: gross,
    lateDeduction: deductions, absenceDeduction: 0, earlyLeaveDeduction: 0, penalties: 0, advances: 0, otherDeductions: 0, totalDeductions: deductions, netSalary: gross - deductions,
  };
}

