// The export route and the voided rule, through the real code on the sample-seeded dev database.

let session: User | null = null;
vi.mock("next/headers", () => ({ cookies: async () => ({ get: () => undefined, set: () => {}, delete: () => {} }) }));
vi.mock("@/lib/auth", () => ({ getSession: async () => session }));

const { GET } = await import("@/app/api/departments/[id]/report/export/route");
const { departmentReport } = await import("@/lib/department-report");
const { getDb } = await import("@/lib/data");

const prisma = new PrismaClient();
let sampleDb = false;
try {
  sampleDb = Boolean(await prisma.user.findUnique({ where: { email: "hr@afroegypt.demo" } }));
} catch {
  sampleDb = false;
}
const VOID_NOTE = "department-report-test";
afterAll(async () => {
  if (sampleDb) {
    await prisma.overtime.deleteMany({ where: { notes: VOID_NOTE } });
    await prisma.deduction.deleteMany({ where: { reason: VOID_NOTE } });
    await prisma.department.deleteMany({ where: { name: VOID_NOTE } });
  }
  await prisma.$disconnect();
});

const call = (id: string) => GET(new NextRequest(`http://x/api/departments/${id}/report/export?range=current`), { params: Promise.resolve({ id }) });

describe("the export route refuses", () => {
  it("without a session (401) and without the departments permission (403)", async () => {
    session = null;
    expect((await call("D1")).status).toBe(401);
    session = user({ role: "supervisor", permissions: ["employees"] });
    expect((await call("D1")).status).toBe(403);
  });

  it.skipIf(!sampleDb)("a department outside the account's departments, or a removed one (404); serves the file otherwise", async () => {
    const depts = await prisma.department.findMany({ where: { deletedAt: null }, orderBy: { id: "asc" }, take: 2 });
    session = user({ role: "supervisor", permissions: ["departments"], departmentIds: [depts[1].id] });
    expect((await call(depts[0].id)).status).toBe(404);
    const removed = await prisma.department.create({ data: { name: VOID_NOTE, deletedAt: new Date() } });
    session = user({ role: "admin" });
    expect((await call(removed.id)).status).toBe(404);
    const ok = await call(depts[1].id);
    expect(ok.status).toBe(200);
    expect(ok.headers.get("Content-Disposition")).toMatch(/department-report-.+\.xlsx/);
    const book = XLSX.read(new Uint8Array(await ok.arrayBuffer()), { type: "array" });
    expect(book.SheetNames).toContain("ملخص");
  });
});

describe.skipIf(!sampleDb)("removed (voided) entries", () => {
  it("never count in any total", async () => {
    const admin = user({ role: "admin" });
    const employee = await prisma.employee.findFirstOrThrow({ where: { deletedAt: null, status: "active", id: { startsWith: "EMP-" } }, orderBy: { id: "asc" } });
    const totals = async () => {
      const db = await getDb();
      const r = (await departmentReport({ all: true }, admin, employee.departmentId, "current", "ar", { db }))!;
      return { overtime: r.overtime!.total.amount, pending: r.overtime!.total.pendingAmount, deductions: r.deductions!.total };
    };
    const before = await totals();
    const date = new Date(`${new Date().toISOString().slice(0, 10)}T00:00:00.000Z`);
    await prisma.overtime.create({ data: { employeeId: employee.id, date, hours: 9, hourlyRate: 1000, amount: 9000, status: "approved", notes: VOID_NOTE, voidedAt: new Date(), voidedBy: "x" } });
    await prisma.deduction.create({ data: { employeeId: employee.id, date, type: "penalty", amount: 9000, reason: VOID_NOTE, voidedAt: new Date(), voidedBy: "x" } });
    expect(await totals()).toEqual(before);
  });
});
